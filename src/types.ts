export interface SignalsConfig {
  /** URL that receives payloads (POST, JSON). Optional when `onPayload` is given. */
  endpoint?: string;
  /** Called with every payload instead of (or as well as) sending it. Handy for demos and tests. */
  onPayload?: (payload: Payload) => void;
  /** Send a batch this often while the page is visible. Default 10 000 ms. */
  flushIntervalMs?: number;
  /** Fraction of page loads that run the SDK at all, 0..1. Decided once per load. Default 1. */
  sampleRate?: number;
  /** When true, nothing is collected until `grantConsent()` is called. Default false. */
  requireConsent?: boolean;
}

export interface Stat {
  n: number;
  mean: number;
  std: number;
}

export interface DeviceSignals {
  userAgent: string;
  platform: string;
  languages: string[];
  timezone: string;
  timezoneOffset: number;
  screen: { width: number; height: number; colorDepth: number; pixelRatio: number };
  hardwareConcurrency: number | null;
  deviceMemory: number | null;
  maxTouchPoints: number;
  cookieEnabled: boolean;
  /** navigator.webdriver: true under most automation tools. A strong bot signal. */
  webdriver: boolean;
  webgl: { vendor: string; renderer: string } | null;
  /** SHA-256 over the stable fields above; null when SubtleCrypto is unavailable (insecure context). */
  hash: string | null;
}

export interface KeystrokeSignals {
  /** Keys pressed in this window. Which keys is never recorded. */
  count: number;
  /** keydown events not generated by the user (event.isTrusted === false), e.g. scripted input. */
  untrusted: number;
  /** How long each key is held down, ms. */
  dwell: Stat;
  /** Gap between releasing one key and pressing the next, ms (gaps over 2 s are ignored as pauses). */
  flight: Stat;
}

export interface Payload {
  /** SDK version. */
  v: string;
  /** Random id for this page load. Not a user or device id. */
  sid: string;
  /** Batch number within this page load, starting at 0. */
  seq: number;
  /** Epoch ms when the batch was built. */
  ts: number;
  /** Sent once, in the first batch after collection starts. */
  device?: DeviceSignals;
  behavior: {
    keystroke?: KeystrokeSignals;
  };
}

/** A collector watches one kind of signal. `snapshot()` returns this window's data and resets it. */
export interface Collector<T> {
  start(): void;
  snapshot(): T | undefined;
  stop(): void;
}

export interface SignalsClient {
  /** Build and send a batch now. Resolves when the payload was handed to the transport. */
  flush(): Promise<void>;
  /** Start collecting when `requireConsent` was set. Safe to call more than once. */
  grantConsent(): void;
  /** Remove every listener and timer. The SDK leaves nothing behind on the page. */
  destroy(): void;
}
